import type { FreePromptBrief } from './lib/free-prompt'

/** Text that goes to the coding AI (en) and its meaning for the student (ko). */
export interface Localized {
  en: string
  ko: string
}

/** One answer a student can pick for a decision. */
export interface DecisionOption {
  value: string
  label: string
  /** what this choice says to the AI */
  text: Localized
  /** acceptance criteria this choice adds to the checklist */
  checklist?: Localized[]
}

export type DecisionKind = 'choice' | 'multi' | 'text'

/**
 * A decision the AI needs made. The student either decides it, delegates it to the AI, or
 * admits they don't know yet — the prompt says which, instead of silently letting the AI guess.
 */
export interface Decision {
  id: string
  group: string
  label: string
  /** the decision's name as the AI reads it (used when it is left undecided) */
  labelEn?: string
  help?: string
  kind: DecisionKind
  /** choice / multi */
  options?: DecisionOption[]
  default?: string | string[]
  /** text: placeholder and how the typed value is phrased ({value} is replaced) */
  placeholder?: string
  text?: Localized
  /** 'core' decisions left unknown are flagged prominently */
  importance?: 'core' | 'nice'
  /** what the prompt says when the student delegates this to the AI (a sensible default otherwise) */
  delegateText?: Localized
}

export interface ReferenceRole {
  id: string
  label: string
  /** how an image with this role is described to the AI; {n} is the image number */
  text: Localized
}

/**
 * The prompt is assembled from sections in this order. `decisions` lists which decisions'
 * texts go in; `auto` sections are generated by the engine (references, undecided items,
 * checklist, locks, process).
 */
export interface PromptSection {
  id: string
  title: Localized
  intro?: Localized
  decisions?: string[]
  auto?: 'references' | 'undecided' | 'checklist' | 'locks' | 'process'
}

/** A concrete thing that can be wrong, and the sentence that asks the AI to fix it. */
export interface Symptom {
  id: string
  label: string
  /** the symptom as the AI reads it */
  labelEn: string
  /** a one-line description so a beginner can recognise it */
  hint?: string
  /** the fix request; {target} is replaced by what the student pointed at */
  fix: Localized
  /** the lesson: why this happens / what the technical term is */
  why?: string
  /** before / after pictures a teacher can add (paths under public/) */
  examples?: Array<{ src: string; caption: string }>
}

export interface DiagnosisCategory {
  id: string
  label: string
  hint?: string
  symptoms: Symptom[]
}

/** How the result differs from the reference image. */
export interface CompareAxis {
  id: string
  label: string
  text: Localized
}

/** Lay words → likely symptoms, so "it looks plasticky" leads somewhere. */
export interface FeelEntry {
  phrase: string
  /** symptom ids, best first */
  symptoms: string[]
  term: string
}

export interface Template {
  id: string
  name: string
  description: string
  version: number
  /** things in the scene the student can point at ("the cliff", "the water"), in both languages */
  targets: Localized[]
  referenceRoles: ReferenceRole[]
  decisions: Decision[]
  sections: PromptSection[]
  /** acceptance criteria that always apply */
  checklistBase: Localized[]
  /** how the AI should work (stages, screenshots, language) */
  process: Localized[]
  diagnosis: DiagnosisCategory[]
  compareAxes: CompareAxis[]
  feelDictionary: FeelEntry[]
}

export interface TemplateIndexEntry {
  id: string
  name: string
  description: string
  file: string
}

export type DecisionState = 'set' | 'delegate' | 'unknown'

export interface DecisionAnswer {
  state: DecisionState
  value?: string | string[]
  /** free text the student wrote instead of (choice) or on top of (multi) the preset options */
  custom?: string
}

/** the value a choice decision takes when the student writes their own answer */
export const CUSTOM = '__custom'

export interface Reference {
  id: string
  role: string
  name: string
  /** downscaled JPEG data URL */
  dataUrl: string
  note?: string
}

export interface Region {
  x: number
  y: number
  w: number
  h: number
}

/** One round of "look at the result → say what's wrong → ask for a fix". */
export interface Iteration {
  id: string
  createdAt: number
  screenshot?: string
  region?: Region
  target: string
  targetEn: string
  categoryId: string
  symptomId: string
  compareId?: string
  referenceId?: string
  note?: string
  promptEn: string
  promptKo: string
  rating?: number
  resolved?: boolean
}

export interface Project {
  id: string
  templateId: string
  name: string
  createdAt: number
  updatedAt: number
  /** The user's own scene brief; omitted by existing template-based projects. */
  freeform?: FreePromptBrief
  decisions: Record<string, DecisionAnswer>
  references: Reference[]
  /** things that are already right and must not change */
  locks: string[]
  iterations: Iteration[]
}
