import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const root = fileURLToPath(new URL('../', import.meta.url))
const bundled = await build({
  absWorkingDir: root,
  entryPoints: ['ui/app.js'],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
})
const script = bundled.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')
const css = (await readFile(new URL('../ui/styles.css', import.meta.url), 'utf8')).replace(/<\/style/gi, '<\\/style')
const html = `<!doctype html>
<html lang="ko"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Prompt Coach · 코칭 시작하기</title><style>${css}</style></head><body><main id="app"><p role="status">코치 화면을 연결하고 있어요…</p></main><script type="module">${script}</script></body></html>`
// A new URI asks hosts to fetch changed HTML instead of reusing a cached widget.
const digest = createHash('sha256').update(html).digest('hex').slice(0, 16)
const resourceUri = `ui://prompt-coach/coach-${digest}.html`
await mkdir(new URL('../generated/', import.meta.url), { recursive: true })
await writeFile(new URL('../generated/coach-ui.mjs', import.meta.url), `// Generated by npm run build:ui; edit ui/ source instead.\nexport const COACH_UI_URI = ${JSON.stringify(resourceUri)};\nexport const COACH_UI_HTML = ${JSON.stringify(html)};\n`)
console.log(`Built self-contained coach UI (${Buffer.byteLength(html)} bytes; no external assets): ${resourceUri}`)
